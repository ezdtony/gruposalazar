<script>
    const slider = document.querySelector('.testimonial-slider');
    const items = document.querySelectorAll('.testimonial-item');
    let currentIndex = 1; // Comienza en el segundo testimonio para tener un testimonio inicial a la izquierda y otro a la derecha
    let autoSlideInterval;

    function updateVisibleItems() {
        items.forEach((item, index) => {
            // Determina qué testimonios mostrar
            if (
                index === currentIndex - 1 ||
                index === currentIndex ||
                index === currentIndex + 1
            ) {
                item.classList.add('visible');
            } else {
                item.classList.remove('visible');
            }
        });

        // Resalta el testimonio central
        items[currentIndex].classList.add('active');
        items[currentIndex - 1]?.classList.remove('active');
        items[currentIndex + 1]?.classList.remove('active');
    }

    function nextSlide() {
        currentIndex = (currentIndex + 1) % items.length;
        updateVisibleItems();
    }

    function prevSlide() {
        currentIndex = (currentIndex - 1 + items.length) % items.length;
        updateVisibleItems();
    }

    function startAutoSlide() {
        autoSlideInterval = setInterval(nextSlide, 3000); // Cambia cada 3 segundos
    }

    function stopAutoSlide() {
        clearInterval(autoSlideInterval);
    }

    // Inicia el carrusel automáticamente
    startAutoSlide();

    // Eventos de botones
    document.querySelector('.btn-next').addEventListener('click', () => {
        stopAutoSlide();
        nextSlide();
        startAutoSlide();
    });

    document.querySelector('.btn-prev').addEventListener('click', () => {
        stopAutoSlide();
        prevSlide();
        startAutoSlide();
    });

    // Detener el auto-slide al pasar el mouse
    slider.addEventListener('mouseover', stopAutoSlide);
    slider.addEventListener('mouseout', startAutoSlide);

    updateVisibleItems(); // Inicializa mostrando tres elementos
</script>